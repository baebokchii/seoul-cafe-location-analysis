-- 추천 지표 표 "추천_지표" 만들기
-- 대상: 최근 12개 분기(2023년 3분기 ~ 2026년 2분기)에 커피-음료 매출이 모두 공개된 상권
-- 기간: 2년 전 4개 분기(20233~20242), 최근 4개 분기(20253~20262)
-- 건수(손님)와 금액(매출)은 그 분기의 월평균이다. 계절 효과를 피하려고 4개 분기 합계끼리 비교한다.

DROP TABLE IF EXISTS "추천_지표";

CREATE TABLE "추천_지표" AS
WITH 분기 AS (
    -- 1단계: 매출(건수·금액)과 점포 수를 분기·상권별로 붙이고, 각 분기가 어느 기간인지 표시
    SELECT
        m."상권_코드",
        m."기준_년분기_코드" AS 분기,
        m."당월_매출_건수"::numeric AS 건수,
        m."당월_매출_금액"::numeric AS 금액,
        p."전체_점포_수"::numeric AS 점포,
        CASE
            WHEN m."기준_년분기_코드" <= '20242' THEN '2년전'
            WHEN m."기준_년분기_코드" >= '20253' THEN '최근'
        END AS 구간
    FROM "커피_매출" m
    JOIN "커피_점포" p USING ("기준_년분기_코드", "상권_코드")
    WHERE m."기준_년분기_코드" BETWEEN '20233' AND '20262'
),
대상 AS (
    -- 2단계: 12개 분기 매출이 모두 있는 상권만 남김
    SELECT "상권_코드"
    FROM 분기
    GROUP BY "상권_코드"
    HAVING COUNT(*) = 12
),
앞분기 AS (
    -- 3단계: 바로 앞 분기의 건수를 옆에 붙임 (데이터 단절 확인용)
    SELECT
        분기.*,
        LAG(건수) OVER (PARTITION BY "상권_코드" ORDER BY 분기) AS 앞_건수
    FROM 분기
    JOIN 대상 USING ("상권_코드")
),
합계 AS (
    -- 4단계: 상권마다 두 기간의 합계·평균을 한 행으로 모음
    -- CASE WHEN에 ELSE가 없으면 조건에 맞지 않는 행은 NULL이 되고, SUM·AVG는 NULL을 건너뛴다
    SELECT
        "상권_코드",
        SUM(CASE WHEN 구간 = '2년전' THEN 건수 END) AS 건수_2년전,
        SUM(CASE WHEN 구간 = '최근' THEN 건수 END) AS 건수_최근,
        SUM(CASE WHEN 구간 = '2년전' THEN 금액 END) AS 금액_2년전,
        SUM(CASE WHEN 구간 = '최근' THEN 금액 END) AS 금액_최근,
        AVG(CASE WHEN 구간 = '2년전' THEN 점포 END) AS 점포_2년전,
        AVG(CASE WHEN 구간 = '최근' THEN 점포 END) AS 점포_최근,
        -- 바로 앞 분기 대비 가장 큰 변화(배수). 올랐으면 건수 / 앞_건수, 내렸으면 앞_건수 / 건수라서 항상 1 이상
        -- 첫 분기는 앞_건수가 NULL이라 MAX에서 빠진다
        MAX(GREATEST(건수 / 앞_건수, 앞_건수 / 건수)) AS 최대_분기_변화
    FROM 앞분기
    GROUP BY "상권_코드"
)
SELECT
    h."상권_코드",
    y."상권_코드_명",
    y."상권_구분_코드_명",
    y."자치구_코드_명",
    ROUND(h.점포_2년전, 1) AS 점포_2년전,
    ROUND(h.점포_최근, 1) AS 점포_최근,
    ROUND((h.건수_최근 / h.건수_2년전 - 1) * 100, 1) AS 손님_2년_증가율,
    ROUND((h.점포_최근 / h.점포_2년전 - 1) * 100, 1) AS 점포_2년_증가율,
    -- 카페 한 곳당 손님을 먼저 구한 뒤 두 기간을 비교
    ROUND(((h.건수_최근 / h.점포_최근) / (h.건수_2년전 / h.점포_2년전) - 1) * 100, 1) AS 점포당_손님_2년_증가율,
    -- 최근 4개 분기 건수 합 ÷ 4 = 최근 1년의 월평균 손님, 이를 평균 카페 수로 나눔
    ROUND(h.건수_최근 / 4 / h.점포_최근) AS 점포당_월_손님,
    ROUND(h.금액_최근 / 4 / h.점포_최근) AS 점포당_월_매출,
    -- 객단가 = 금액 ÷ 건수(결제 한 번에 쓰는 돈). 두 기간의 객단가를 비교
    ROUND(((h.금액_최근 / h.건수_최근) / (h.금액_2년전 / h.건수_2년전) - 1) * 100, 1) AS 객단가_2년_변화율,
    h.최대_분기_변화
FROM 합계 h
JOIN "영역" y USING ("상권_코드");

ALTER TABLE "추천_지표" ADD PRIMARY KEY ("상권_코드");
