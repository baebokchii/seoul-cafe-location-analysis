-- 03_후보_선정.sql
-- 5단계 후보 선정. 상권마다 최근 4개 분기와 그 전 4개 분기를 요약하고
-- 거르는 기준을 하나씩 통과했는지 표시한 테이블(후보_지표)을 만든다.
-- 06 노트북 맨 앞에서 실행함 (주석 안에 세미콜론 쓰지 말 것)
--
--   최근 4분기 : 2025Q3, 2025Q4, 2026Q1, 2026Q2
--   이전 4분기 : 2024Q3, 2024Q4, 2025Q1, 2025Q2
--
-- 처음에는 윈도 함수 AVG() OVER (ROWS BETWEEN 3 PRECEDING ...)로 4분기 평균을 내려고 했음.
-- 그런데 매출이 비공개인 분기는 줄 자체가 없어서 "3줄 전"이 4분기 전이 아닐 수 있음
-- (성장률 LAG 때와 같은 함정, 이슈 로그 8번).
-- 그래서 분기 코드를 직접 적고 GROUP BY로 평균을 내는 쪽으로 바꿈. 빠진 분기는 COUNT로 잡아냄.
--
-- 기준 바꾼 기록 (2026-11-11)
--   처음 상위 10곳을 보고 나서 경쟁 쪽을 보강함. 대형 프랜차이즈와 정면으로 붙는 걸 피하기 위해서.
--   ③ 추세 : "줄지 않음(>=)" → "올라감(>)"
--   ④ 경쟁 : 프랜차이즈 비중이 중앙값보다 낮을 것 (새로 넣음)

DROP TABLE IF EXISTS 후보_지표;

CREATE TABLE 후보_지표 AS
WITH

-- 1) 최근 4분기 요약
최근 AS (
    SELECT
        상권_코드,
        COUNT(*)              AS 최근_분기_수,     -- 4가 아니면 매출이 빠진 분기가 있는 것
        SUM(결제부족)         AS 결제부족_분기_수,
        AVG(점포당_매출)      AS 최근_점포당_매출,
        AVG(매출)             AS 최근_상권_매출,
        AVG(오전점심_비중)    AS 오전점심_비중,
        AVG(주중_비중)        AS 주중_비중,
        AVG(프랜차이즈_비중)  AS 프랜차이즈_비중,
        AVG(폐업률)           AS 폐업률
    FROM 분석_대상
    WHERE 기준_년분기_코드 IN (20253, 20254, 20261, 20262)
    GROUP BY 상권_코드
),

-- 2) 이전 4분기 요약 (추세 비교용). 결제부족인 분기는 빼고 셈
이전 AS (
    SELECT
        상권_코드,
        COUNT(*)          AS 이전_분기_수,
        AVG(점포당_매출)  AS 이전_점포당_매출,
        AVG(매출)         AS 이전_상권_매출
    FROM 분석_대상
    WHERE 기준_년분기_코드 IN (20243, 20244, 20251, 20252)
      AND 결제부족 = 0
    GROUP BY 상권_코드
),

-- 3) 2026Q2 기준 상권 정보 (이름, 유형, 직장인구 등)
현재 AS (
    SELECT
        상권_코드, 상권_코드_명, 상권_유형, 자치구,
        점포_수, 직장인구, 지하철역_수, 관공서_수
    FROM 분석_대상
    WHERE 기준_년분기_코드 = 20262
),

-- 4) 기준 ① 데이터 신뢰: 최근 4분기 모두 매출이 있고 결제부족인 분기가 없음
신뢰 AS (
    SELECT 상권_코드
    FROM 최근
    WHERE 최근_분기_수 = 4
      AND 결제부족_분기_수 = 0
),

-- 5) 기준 ②, ④에 쓸 서울 중앙값. ①을 통과한 상권들 사이의 중앙값으로 잡음
--    PERCENTILE_CONT(0.5)가 중앙값. WITHIN GROUP 안에 무엇 기준으로 줄 세울지 적음
중앙값 AS (
    SELECT
        PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY 최근.오전점심_비중)   AS 오전점심_중앙값,
        PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY 최근.주중_비중)       AS 주중_중앙값,
        PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY 최근.프랜차이즈_비중) AS 프랜차이즈_중앙값
    FROM 최근
    JOIN 신뢰 ON 최근.상권_코드 = 신뢰.상권_코드
),

-- 6) 다 붙이고 기준마다 통과 여부를 0/1로 표시
--    뒤 기준은 앞 기준을 통과한 상권만 통과할 수 있게 앞 조건을 같이 적음
표시 AS (
    SELECT
        h.상권_코드,
        h.상권_코드_명,
        h.상권_유형,
        h.자치구,
        h.점포_수,
        h.직장인구,
        h.지하철역_수,
        h.관공서_수,
        r.최근_점포당_매출,
        b.이전_점포당_매출,
        r.최근_점포당_매출 / b.이전_점포당_매출 - 1 AS 추세,
        r.최근_상권_매출 / b.이전_상권_매출 - 1     AS 상권_매출_추세,   -- 거르지 않고 보여 주기만 함
        r.오전점심_비중,
        r.주중_비중,
        r.프랜차이즈_비중,
        r.폐업률,
        m.오전점심_중앙값,
        m.주중_중앙값,
        m.프랜차이즈_중앙값,

        CASE WHEN r.최근_분기_수 = 4 AND r.결제부족_분기_수 = 0
             THEN 1 ELSE 0 END AS 통과1_신뢰,

        CASE WHEN r.최근_분기_수 = 4 AND r.결제부족_분기_수 = 0
              AND r.오전점심_비중 >= m.오전점심_중앙값
              AND r.주중_비중 >= m.주중_중앙값
             THEN 1 ELSE 0 END AS 통과2_콘셉트,

        CASE WHEN r.최근_분기_수 = 4 AND r.결제부족_분기_수 = 0
              AND r.오전점심_비중 >= m.오전점심_중앙값
              AND r.주중_비중 >= m.주중_중앙값
              AND b.이전_분기_수 = 4                          -- 이전 4분기도 다 있어야 비교 가능
              AND r.최근_점포당_매출 > b.이전_점포당_매출      -- 올라간 상권만
             THEN 1 ELSE 0 END AS 통과3_추세,

        CASE WHEN r.최근_분기_수 = 4 AND r.결제부족_분기_수 = 0
              AND r.오전점심_비중 >= m.오전점심_중앙값
              AND r.주중_비중 >= m.주중_중앙값
              AND b.이전_분기_수 = 4
              AND r.최근_점포당_매출 > b.이전_점포당_매출
              AND r.프랜차이즈_비중 < m.프랜차이즈_중앙값      -- 대형 프랜차이즈가 적은 상권
             THEN 1 ELSE 0 END AS 통과4_경쟁
    FROM 현재 h
    JOIN 최근 r      ON h.상권_코드 = r.상권_코드
    LEFT JOIN 이전 b ON h.상권_코드 = b.상권_코드
    CROSS JOIN 중앙값 m                                       -- 중앙값은 한 줄짜리라 모든 상권에 같은 값이 붙음
),

-- 7) 네 기준을 다 통과한 상권끼리 최근 점포당 매출 순위
순위 AS (
    SELECT
        상권_코드,
        RANK() OVER (ORDER BY 최근_점포당_매출 DESC) AS 순위
    FROM 표시
    WHERE 통과4_경쟁 = 1
)

SELECT
    표시.*,
    순위.순위
FROM 표시
LEFT JOIN 순위 ON 표시.상권_코드 = 순위.상권_코드;

ALTER TABLE 후보_지표 ADD PRIMARY KEY (상권_코드);
