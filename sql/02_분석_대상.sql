-- 02_분석_대상.sql
-- 가설 검증에 쓸 뷰. 분석_상권분기에서 매출이 있는 줄만 가져와서
-- 03 노트북에서 정한 제외 표시랑 로그 값을 붙인다.
-- 04, 05 노트북 맨 앞에서 이 파일을 읽어서 실행함 (주석 안에 세미콜론 쓰지 말 것)
--
-- 테이블 말고 뷰로 만든 이유: 원본 테이블(분석_상권분기)이 바뀌면 뷰도 알아서 따라감.
-- 계산이 가벼워서 매번 다시 계산해도 느리지 않음

DROP VIEW IF EXISTS 분석_대상;

CREATE VIEW 분석_대상 AS
SELECT
    기준_년분기_코드,
    상권_코드,
    상권_코드_명,
    상권_유형,
    자치구,
    점포_수,
    매출,
    매출_건수,
    점포당_매출,
    폐업률,
    오전점심_비중,
    주중_비중,
    직장인구,
    상주인구,
    유동인구,
    오전점심_유동인구,
    지하철역_수,
    관공서_수,
    프랜차이즈_비중,      -- 5단계 후보 선정의 경쟁 기준에서 씀

    매출_건수::numeric / 점포_수 AS 점포당_건수,

    -- 03 노트북에서 정한 규칙
    -- 점포 하나에 분기 결제가 90건(하루 1건) 미만이면 결제가 거의 안 잡힌 줄로 보고 본 분석에서 뺌.
    -- 지우지 않고 표시만 해 둬야 "포함했을 때" 결과도 같이 볼 수 있음
    CASE
        WHEN 매출_건수::numeric / 점포_수 < 90 THEN 1
        ELSE 0
    END AS 결제부족,

    -- 자연로그. LN(0)은 에러가 나는데 매출이 있는 줄에는 0인 값이 없는 걸 확인함
    -- (직장인구 최솟값 1, 상주인구 1, 유동인구 8)
    LN(점포당_매출)        AS ln_점포당_매출,
    LN(직장인구)           AS ln_직장인구,
    LN(상주인구)           AS ln_상주인구,
    LN(유동인구)           AS ln_유동인구,
    LN(오전점심_유동인구)  AS ln_오전점심_유동인구,
    LN(점포_수)            AS ln_점포_수
FROM 분석_상권분기
WHERE 매출 IS NOT NULL;
