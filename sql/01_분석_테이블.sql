-- 01_분석_테이블.sql
-- 원본 테이블에서 커피-음료만 뽑아서 "상권 x 분기" 한 줄짜리 분석 테이블을 만든다.
-- notebooks/02_전처리_검증.ipynb 맨 앞에서 이 파일을 읽어서 실행함.
-- 주의: 노트북에서 세미콜론 기준으로 잘라서 실행하니까 주석 안에는 세미콜론 쓰지 말 것

DROP TABLE IF EXISTS 분석_상권분기;

CREATE TABLE 분석_상권분기 AS
WITH

-- 1) 커피 점포
--    2025년부터 점포 수 컬럼 이름이 바뀌었음
--      2024년까지 : 유사_업종_점포_수 (= 점포_수 + 프랜차이즈_점포_수)
--      2025년부터 : 전체_점포_수     (= 일반_점포_수 + 프랜차이즈_점포_수)
--    둘이 같은 뜻이라 하나로 합침.
--    옛날 점포_수를 그대로 이어 붙이면 2025년에 점포가 갑자기 33% 늘어난 것처럼 보임
커피_점포 AS (
    SELECT
        기준_년분기_코드,
        상권_코드,
        CASE
            WHEN 기준_년분기_코드 >= 20251 THEN 전체_점포_수
            ELSE 유사_업종_점포_수
        END::int AS 점포_수,
        프랜차이즈_점포_수::int AS 프랜차이즈_점포_수,
        폐업_률 AS 폐업률
    FROM 원본_점포
    WHERE 서비스_업종_코드_명 = '커피-음료'
),

-- 2) 커피 매출. 금액은 분기 매출로 봄 (데이터셋 설명에 "분기당 매출 금액")
--    오전점심 = 06~11시 + 11~14시 (출근 시간 + 점심 시간)
커피_매출 AS (
    SELECT
        기준_년분기_코드,
        상권_코드,
        당월_매출_금액 AS 매출,
        당월_매출_건수 AS 매출_건수,
        주중_매출_금액 AS 주중_매출,
        시간대_06_11_매출_금액 + 시간대_11_14_매출_금액 AS 오전점심_매출
    FROM 원본_추정매출
    WHERE 서비스_업종_코드_명 = '커피-음료'
),

-- 3) 유동인구도 06~14시만 따로 더해 둠 (H2에서 전체 유동인구랑 비교할 것)
유동 AS (
    SELECT
        기준_년분기_코드,
        상권_코드,
        총_유동인구_수 AS 유동인구,
        시간대_06_11_유동인구_수 + 시간대_11_14_유동인구_수 AS 오전점심_유동인구
    FROM 원본_길단위인구
),

직장 AS (
    SELECT 기준_년분기_코드, 상권_코드, 총_직장_인구_수 AS 직장인구
    FROM 원본_직장인구
),

상주 AS (
    SELECT 기준_년분기_코드, 상권_코드, 총_상주인구_수 AS 상주인구
    FROM 원본_상주인구
),

-- 4) 집객시설. 빈 칸 = 시설 없음이라서 0으로 바꿈 (값이 있는 칸의 최솟값이 1)
--    직장인 수요랑 관련 있어 보이는 것만 가져옴
집객 AS (
    SELECT
        기준_년분기_코드,
        상권_코드,
        COALESCE(집객시설_수, 0)  AS 집객시설_수,
        COALESCE(지하철_역_수, 0)  AS 지하철역_수,
        COALESCE(버스_정거장_수, 0) AS 버스정류장_수,
        COALESCE(관공서_수, 0)    AS 관공서_수,
        COALESCE(은행_수, 0)      AS 은행_수,
        COALESCE(대학교_수, 0)    AS 대학교_수
    FROM 원본_집객시설
),

-- 5) 전부 붙이기. 기준은 커피 점포 테이블
--    매출이 비공개인 분기도 일단 남겨 둠 (매출 칸만 비어 있음)
합친 AS (
    SELECT
        p.기준_년분기_코드,
        p.상권_코드,
        a.상권_코드_명,
        a.상권_구분_코드_명 AS 상권_유형,
        a.자치구_코드_명    AS 자치구,
        a.행정동_코드_명    AS 행정동,
        p.점포_수,
        p.프랜차이즈_점포_수,
        p.폐업률,
        s.매출,
        s.매출_건수,
        s.주중_매출,
        s.오전점심_매출,
        f.유동인구,
        f.오전점심_유동인구,
        w.직장인구,
        r.상주인구,
        -- 집객시설 파일에 아예 없는 상권도 있어서 여기서 한 번 더 0 처리
        COALESCE(g.집객시설_수, 0)   AS 집객시설_수,
        COALESCE(g.지하철역_수, 0)   AS 지하철역_수,
        COALESCE(g.버스정류장_수, 0) AS 버스정류장_수,
        COALESCE(g.관공서_수, 0)     AS 관공서_수,
        COALESCE(g.은행_수, 0)       AS 은행_수,
        COALESCE(g.대학교_수, 0)     AS 대학교_수
    FROM 커피_점포 p
    JOIN 원본_영역 a
        ON p.상권_코드 = a.상권_코드
    LEFT JOIN 커피_매출 s
        ON p.상권_코드 = s.상권_코드 AND p.기준_년분기_코드 = s.기준_년분기_코드
    LEFT JOIN 유동 f
        ON p.상권_코드 = f.상권_코드 AND p.기준_년분기_코드 = f.기준_년분기_코드
    LEFT JOIN 직장 w
        ON p.상권_코드 = w.상권_코드 AND p.기준_년분기_코드 = w.기준_년분기_코드
    LEFT JOIN 상주 r
        ON p.상권_코드 = r.상권_코드 AND p.기준_년분기_코드 = r.기준_년분기_코드
    LEFT JOIN 집객 g
        ON p.상권_코드 = g.상권_코드 AND p.기준_년분기_코드 = g.기준_년분기_코드
    WHERE a.상권_구분_코드_명 <> '관광특구'   -- 2단계에서 관광특구는 빼기로 함
      AND p.점포_수 > 0                       -- 점포가 0개면 점포당 매출을 못 구함
),

-- 6) 지표 계산
--    정수끼리 나누면 소수점이 날아가서 앞에 ::numeric을 붙임
지표 AS (
    SELECT
        *,
        매출::numeric / 점포_수                     AS 점포당_매출,
        오전점심_매출::numeric / NULLIF(매출, 0)     AS 오전점심_비중,
        주중_매출::numeric / NULLIF(매출, 0)         AS 주중_비중,
        프랜차이즈_점포_수::numeric / 점포_수         AS 프랜차이즈_비중
    FROM 합친
)

-- 7) 전년 같은 분기 대비 성장률
--    LAG(값, 4)로 4줄 전(= 4분기 전) 값을 가져옴.
--    그런데 중간에 빠진 분기가 있으면 4줄 전이 1년 전이 아니게 됨.
--    그래서 4줄 전 분기 코드가 지금 코드 - 10일 때만 계산함 (예: 20262 - 10 = 20252)
SELECT
    *,
    CASE
        WHEN LAG(기준_년분기_코드, 4) OVER w = 기준_년분기_코드 - 10
        THEN 점포당_매출 / NULLIF(LAG(점포당_매출, 4) OVER w, 0) - 1
    END AS 점포당_매출_성장률
FROM 지표
WINDOW w AS (PARTITION BY 상권_코드 ORDER BY 기준_년분기_코드);

-- 상권 + 분기가 한 줄씩만 있는지 기본키로 확인 (중복이 있으면 여기서 에러가 남)
ALTER TABLE 분석_상권분기 ADD PRIMARY KEY (상권_코드, 기준_년분기_코드);
